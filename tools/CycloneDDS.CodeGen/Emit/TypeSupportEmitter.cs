using System.Text;
using CycloneDDS.CodeGen.Model;
using CycloneDDS.Compiler.Common.IdlJson;

namespace CycloneDDS.CodeGen.Emit
{
    /// <summary>
    /// Emits the partial declaration that makes a <see cref="StructType"/> an
    /// <c>IDdsType&lt;T&gt;</c>: its idlc topic descriptor plus an XCDR1 serializer and
    /// deserializer that walk the same <see cref="Shape"/>s the IDL was rendered from.
    /// </summary>
    public static class TypeSupportEmitter
    {
        private const string Core = "global::CycloneDDS.Core";

        public static string Emit(StructType type, JsonTopicDescriptor descriptor)
        {
            var sb = new StringBuilder();
            string self = type.CSharpReference;
            string iface = $"{Core}.IDdsType<{self}>";

            sb.AppendLine("// <auto-generated>Generated by CycloneDDS.CodeGen. Do not edit.</auto-generated>");
            sb.AppendLine("#nullable disable");
            sb.AppendLine();

            bool hasNamespace = type.Namespace.Length > 0;
            string indent = hasNamespace ? "    " : "";
            if (hasNamespace)
            {
                sb.AppendLine($"namespace {type.Namespace}");
                sb.AppendLine("{");
            }

            sb.AppendLine($"{indent}partial {type.DeclarationKind} {type.Name} : {iface}");
            sb.AppendLine($"{indent}{{");

            var body = new CodeBlock(sb, indent + "    ");
            EmitDescriptor(body, type, descriptor, iface);
            sb.AppendLine();
            EmitSerialize(body, type, iface);
            sb.AppendLine();
            EmitDeserialize(body, type, iface);

            sb.AppendLine($"{indent}}}");
            if (hasNamespace) sb.AppendLine("}");
            return sb.ToString();
        }

        private static void EmitDescriptor(CodeBlock code, StructType type, JsonTopicDescriptor descriptor, string iface)
        {
            string ops = string.Join(", ", descriptor.Ops.Select(op => $"0x{(uint)op:x8}u"));

            code.Line($"private static readonly {Core}.DdsTypeDescriptor __ddsDescriptor = new(");
            code.Line($"    \"{type.IdlName}\",");
            code.Line($"    new uint[] {{ {ops} }},");
            code.Line($"    flagset: {descriptor.FlagSet}u, size: {descriptor.Size}u, align: {descriptor.Align}u);");
            code.Line("");
            code.Line($"static {Core}.DdsTypeDescriptor {iface}.Descriptor => __ddsDescriptor;");
        }


        // ---- Serialize -------------------------------------------------------------

        private static void EmitSerialize(CodeBlock code, StructType type, string iface)
        {
            code.Line($"static void {iface}.Serialize(ref {Core}.CdrWriter writer, in {type.CSharpReference} value)");
            code.Open();
            for (int i = 0; i < type.Fields.Count; i++)
            {
                var field = type.Fields[i];
                WriteMember(code, field.Shape, $"value.{field.Name}", $"{type.Name}.{field.Name}", i);
            }
            code.Close();
        }

        private static void WriteMember(CodeBlock code, Shape shape, string access, string member, int index)
        {
            switch (shape)
            {
                case SequenceShape seq:
                    code.Open();
                    code.Line($"global::System.ReadOnlySpan<{ElementType(seq.Element)}> __span{index} = {SpanSource(seq.Kind, access)};");
                    code.Line($"writer.WriteSequenceLength(__span{index}.Length, {seq.Bound}, \"{member}\");");
                    WriteElements(code, seq.Element, $"__span{index}", member, index);
                    code.Close();
                    break;

                case ArrayShape array:
                    code.Open();
                    code.Line($"global::System.ReadOnlySpan<{ElementType(array.Element)}> __span{index} = {SpanSource(array.Kind, access)};");
                    if (array.Kind != CollectionKind.InlineArray)
                    {
                        // A null array writes default elements; any other length is a caller error
                        code.Line($"if ({access} == null) __span{index} = new {ElementType(array.Element)}[{array.Length}];");
                        code.Line($"else if (__span{index}.Length != {array.Length}) {Core}.CdrWriter.ThrowArrayLength(\"{member}\", {array.Length}, __span{index}.Length);");
                    }
                    WriteElements(code, array.Element, $"__span{index}", member, index);
                    code.Close();
                    break;

                default:
                    code.Line(WriteScalar(shape, access, member));
                    break;
            }
        }

        private static void WriteElements(CodeBlock code, Shape element, string span, string member, int index)
        {
            switch (element)
            {
                case PrimitiveShape { Kind: PrimitiveKind.Bool }:
                    code.Line($"writer.WriteBools({span});");
                    break;

                case PrimitiveShape:
                    code.Line($"writer.WritePrimitives({span});");
                    break;

                default:
                    code.Line($"foreach (ref readonly var __item{index} in {span})");
                    code.Line($"    {WriteScalar(element, $"__item{index}", member)}");
                    break;
            }
        }

        private static string WriteScalar(Shape shape, string access, string member) => shape switch
        {
            PrimitiveShape p => $"writer.Write{p.Kind.CdrMethodSuffix()}({access});",
            EnumShape e => $"writer.Write{WireKind(e.Type).CdrMethodSuffix()}(unchecked(({WireKind(e.Type).CSharpKeyword()}){access}));",
            StringShape { Wide: false } s => $"writer.WriteString({access}, {s.Bound}, \"{member}\");",
            StringShape s => $"writer.WriteWideString({access}, {s.Bound}, \"{member}\");",
            StructShape => $"writer.WriteStruct({access}, \"{member}\");",
            _ => throw new InvalidOperationException($"No scalar writer for {shape}."),
        };

        /// <summary>Expression converting a collection member to a span over its elements.</summary>
        private static string SpanSource(CollectionKind kind, string access) => kind switch
        {
            CollectionKind.List => $"global::System.Runtime.InteropServices.CollectionsMarshal.AsSpan({access})",
            _ => access,
        };


        // ---- Deserialize -----------------------------------------------------------

        private static void EmitDeserialize(CodeBlock code, StructType type, string iface)
        {
            code.Line($"static {type.CSharpReference} {iface}.Deserialize(ref {Core}.CdrReader reader)");
            code.Open();
            code.Line($"var value = new {type.CSharpReference}();");
            for (int i = 0; i < type.Fields.Count; i++)
            {
                var field = type.Fields[i];
                ReadMember(code, field.Shape, $"value.{field.Name}", i);
            }
            code.Line("return value;");
            code.Close();
        }

        private static void ReadMember(CodeBlock code, Shape shape, string target, int index)
        {
            switch (shape)
            {
                case SequenceShape seq:
                    code.Open();
                    code.Line($"int __count{index} = reader.ReadSequenceLength({MinimumSize(seq.Element)});");
                    ReadCollection(code, seq.Element, seq.Kind, target, $"__count{index}", index);
                    code.Close();
                    break;

                case ArrayShape { Kind: CollectionKind.InlineArray } array:
                    code.Open();
                    code.Line($"global::System.Span<{ElementType(array.Element)}> __span{index} = {target};");
                    ReadIntoSpan(code, array.Element, $"__span{index}", index);
                    code.Close();
                    break;

                case ArrayShape array:
                    code.Open();
                    ReadCollection(code, array.Element, CollectionKind.Array, target, array.Length.ToString(), index);
                    code.Close();
                    break;

                default:
                    code.Line($"{target} = {ReadScalar(shape)};");
                    break;
            }
        }

        private static void ReadCollection(CodeBlock code, Shape element, CollectionKind kind, string target, string count, int index)
        {
            string elementType = ElementType(element);

            if (element is PrimitiveShape { Kind: not PrimitiveKind.Bool })
            {
                string method = kind == CollectionKind.List ? "ReadPrimitiveList" : "ReadPrimitiveArray";
                code.Line($"{target} = reader.{method}<{elementType}>({count});");
                return;
            }

            if (kind == CollectionKind.List)
            {
                code.Line($"var __list{index} = new global::System.Collections.Generic.List<{elementType}>({count});");
                code.Line($"global::System.Runtime.InteropServices.CollectionsMarshal.SetCount(__list{index}, {count});");
                ReadIntoSpan(code, element, $"global::System.Runtime.InteropServices.CollectionsMarshal.AsSpan(__list{index})", index);
                code.Line($"{target} = __list{index};");
            }
            else
            {
                code.Line($"var __array{index} = new {elementType}[{count}];");
                ReadIntoSpan(code, element, $"global::System.MemoryExtensions.AsSpan(__array{index})", index);
                code.Line($"{target} = __array{index};");
            }
        }

        private static void ReadIntoSpan(CodeBlock code, Shape element, string span, int index)
        {
            switch (element)
            {
                case PrimitiveShape { Kind: PrimitiveKind.Bool }:
                    code.Line($"reader.ReadBools({span});");
                    break;

                case PrimitiveShape:
                    code.Line($"reader.ReadPrimitives({span});");
                    break;

                default:
                    code.Line($"foreach (ref var __item{index} in {span})");
                    code.Line($"    __item{index} = {ReadScalar(element)};");
                    break;
            }
        }

        private static string ReadScalar(Shape shape) => shape switch
        {
            PrimitiveShape p => $"reader.Read{p.Kind.CdrMethodSuffix()}()",
            EnumShape e => $"unchecked(({e.Type.CSharpReference})reader.Read{WireKind(e.Type).CdrMethodSuffix()}())",
            StringShape { Wide: false } => "reader.ReadString()",
            StringShape => "reader.ReadWideString()",
            StructShape s => $"reader.ReadStruct<{s.Type.CSharpReference}>()",
            _ => throw new InvalidOperationException($"No scalar reader for {shape}."),
        };

        /// <summary>Smallest serialized element size, so a corrupt sequence count is caught before allocating.</summary>
        private static int MinimumSize(Shape element) => element switch
        {
            PrimitiveShape p => p.Kind.Size(),
            EnumShape e => e.Type.Underlying.Size(),
            StringShape => 4,
            _ => 1,
        };


        // ---- Shared ----------------------------------------------------------------

        private static string ElementType(Shape element) => element switch
        {
            PrimitiveShape p => p.Kind.CSharpKeyword(),
            EnumShape e => e.Type.CSharpReference,
            StringShape => "string",
            StructShape s => s.Type.CSharpReference,
            _ => throw new InvalidOperationException($"{element} cannot be a collection element."),
        };

        /// <summary>
        /// Enums travel as an unsigned integer of their bit bound (Cyclone's representation),
        /// except that 32-bit signed enums keep int32 so their C# cast stays value-preserving.
        /// </summary>
        private static PrimitiveKind WireKind(EnumType type) => type.BitBound switch
        {
            8 => PrimitiveKind.Byte,
            16 => PrimitiveKind.UInt16,
            _ => type.Underlying == PrimitiveKind.UInt32 ? PrimitiveKind.UInt32 : PrimitiveKind.Int32,
        };

        /// <summary>Indented line writer for a brace-delimited block.</summary>
        private sealed class CodeBlock(StringBuilder sb, string indent)
        {
            private string _indent = indent;

            public void Line(string text) => sb.AppendLine(text.Length == 0 ? "" : _indent + text);

            public void Open()
            {
                Line("{");
                _indent += "    ";
            }

            public void Close()
            {
                _indent = _indent[..^4];
                Line("}");
            }
        }
    }
}
