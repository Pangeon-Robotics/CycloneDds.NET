using System.Text;
using System.Text.RegularExpressions;
using CycloneDDS.CodeGen.Discovery;
using CycloneDDS.CodeGen.Model;

namespace CycloneDDS.CodeGen.Emit
{
    /// <summary>
    /// Renders the local types of a <see cref="DdsSchema"/> as IDL, one file per
    /// <see cref="NamedType.IdlFile"/>. The IDL is the input idlc derives topic descriptors from,
    /// and the interface published to other DDS implementations.
    /// </summary>
    public static class IdlEmitter
    {
        // IDL 4.2 keywords plus the integer aliases; an identifier equal to one, ignoring case, must be escaped
        private static readonly HashSet<string> Keywords = new(StringComparer.OrdinalIgnoreCase)
        {
            "abstract", "any", "alias", "attribute", "bitfield", "bitmask", "bitset", "boolean", "case", "char",
            "component", "connector", "const", "consumes", "context", "custom", "default", "double", "emits", "enum",
            "eventtype", "exception", "factory", "false", "finder", "fixed", "float", "getraises", "getter", "home",
            "import", "in", "inout", "interface", "local", "long", "manages", "map", "mirrorport", "module", "multiple",
            "native", "object", "octet", "oneway", "out", "primarykey", "private", "port", "porttype", "provides",
            "public", "publishes", "raises", "readonly", "setraises", "setter", "sequence", "short", "string", "struct",
            "supports", "switch", "true", "truncatable", "typedef", "typeid", "typename", "typeprefix", "unsigned",
            "union", "uses", "valuebase", "valuetype", "void", "wchar", "wstring", "int8", "uint8", "int16", "int32",
            "int64", "uint16", "uint32", "uint64",
        };

        /// <summary>
        /// Returns the IDL text of every local IDL file, keyed by file name without extension.
        /// Include cycles between files are reported on <paramref name="schema"/>.
        /// </summary>
        public static Dictionary<string, string> Emit(DdsSchema schema)
        {
            var files = schema.LocalTypes.GroupBy(t => t.IdlFile).ToDictionary(g => g.Key, g => g.ToList());
            var includes = files.ToDictionary(f => f.Key, f => Includes(f.Key, f.Value));

            ReportIncludeCycles(schema, includes);

            return files.ToDictionary(f => f.Key, f => EmitFile(f.Key, f.Value, includes[f.Key]));
        }

        private static string EmitFile(string file, List<NamedType> types, SortedSet<string> includes)
        {
            var sb = new StringBuilder();
            string guard = $"CYCLONEDDS_GENERATED_{Regex.Replace(file.ToUpperInvariant(), "[^A-Z0-9_]", "_")}_IDL";

            sb.AppendLine("// Generated by CycloneDDS.CodeGen from C# sources. Do not edit.");
            sb.AppendLine($"#ifndef {guard}");
            sb.AppendLine($"#define {guard}");
            sb.AppendLine();

            foreach (var include in includes)
                sb.AppendLine($"#include \"{include}.idl\"");
            if (includes.Count > 0)
                sb.AppendLine();

            // Modules are reopened as needed so dependencies always precede their users
            var open = new List<string>();
            foreach (var type in DependencyOrder(types))
            {
                var target = type.IdlModule.Length == 0 ? [] : type.IdlModule.Split("::").ToList();

                int common = 0;
                while (common < open.Count && common < target.Count && open[common] == target[common]) common++;

                while (open.Count > common)
                {
                    open.RemoveAt(open.Count - 1);
                    sb.AppendLine($"{Indent(open.Count)}}};");
                }
                while (open.Count < target.Count)
                {
                    sb.AppendLine($"{Indent(open.Count)}module {target[open.Count]} {{");
                    open.Add(target[open.Count]);
                }

                if (type is StructType structType) EmitStruct(sb, structType, open.Count);
                else EmitEnum(sb, (EnumType)type, open.Count);
            }

            for (int depth = open.Count - 1; depth >= 0; depth--)
                sb.AppendLine($"{Indent(depth)}}};");

            sb.AppendLine();
            sb.AppendLine($"#endif // {guard}");
            return sb.ToString();
        }

        private static void EmitStruct(StringBuilder sb, StructType type, int depth)
        {
            string indent = Indent(depth);

            sb.AppendLine($"{indent}@final");
            sb.AppendLine($"{indent}struct {type.Name} {{");
            foreach (var field in type.Fields)
            {
                var (typeSpec, suffix) = Declarator(field.Shape);
                sb.AppendLine($"{indent}    {typeSpec} {Identifier(field.Name)}{suffix};");
            }
            sb.AppendLine($"{indent}}};");
            sb.AppendLine();
        }

        private static void EmitEnum(StringBuilder sb, EnumType type, int depth)
        {
            string indent = Indent(depth);

            // Implicit values only when they are exactly 0..n-1 in declaration order
            bool explicitValues = type.Members.Select((m, i) => m.Value != i).Any(differs => differs);

            if (type.BitBound != 32)
                sb.AppendLine($"{indent}@bit_bound({type.BitBound})");
            sb.AppendLine($"{indent}enum {type.Name} {{");
            for (int i = 0; i < type.Members.Count; i++)
            {
                var member = type.Members[i];
                string value = explicitValues ? $"@value({member.Value}) " : "";
                string comma = i < type.Members.Count - 1 ? "," : "";
                sb.AppendLine($"{indent}    {value}{Identifier(member.Name)}{comma}");
            }
            sb.AppendLine($"{indent}}};");
            sb.AppendLine();
        }

        /// <summary>IDL type spec and declarator suffix of a member: arrays put their length after the name.</summary>
        private static (string TypeSpec, string Suffix) Declarator(Shape shape) => shape switch
        {
            ArrayShape array => (TypeSpec(array.Element), $"[{array.Length}]"),
            _ => (TypeSpec(shape), ""),
        };

        private static string TypeSpec(Shape shape) => shape switch
        {
            PrimitiveShape p => p.Kind.IdlName(),
            EnumShape e => ScopedName(e.Type),
            StructShape s => ScopedName(s.Type),
            StringShape { Wide: false, Bound: 0 } => "string",
            StringShape { Wide: false } str => $"string<{str.Bound}>",
            StringShape { Bound: 0 } => "wstring",
            StringShape str => $"wstring<{str.Bound}>",
            SequenceShape { Bound: 0 } seq => $"sequence<{CloseableSpec(seq.Element)}>",
            SequenceShape seq => $"sequence<{TypeSpec(seq.Element)}, {seq.Bound}>",
            _ => throw new InvalidOperationException($"No IDL type spec for {shape}."),
        };

        /// <summary>A type spec followed directly by '>': idlc lexes '>>' as a shift, so separate them.</summary>
        private static string CloseableSpec(Shape shape)
        {
            string spec = TypeSpec(shape);
            return spec.EndsWith('>') ? spec + " " : spec;
        }

        /// <summary>Absolute scoped name, so lookup never depends on the enclosing module.</summary>
        private static string ScopedName(NamedType type) => $"::{type.IdlName}";

        private static string Identifier(string name) => Keywords.Contains(name) ? $"_{name}" : name;

        private static string Indent(int depth) => new(' ', depth * 4);


        // ---- Ordering and includes -------------------------------------------------

        /// <summary>The types of one file, each after the same-file types it references.</summary>
        private static List<NamedType> DependencyOrder(List<NamedType> types)
        {
            var inFile = types.ToHashSet();
            var ordered = new List<NamedType>();
            var visited = new HashSet<NamedType>();

            foreach (var type in types)
                Visit(type);
            return ordered;

            // Recursion among local structs was rejected during discovery
            void Visit(NamedType type)
            {
                if (!visited.Add(type)) return;
                foreach (var dependency in Dependencies(type).Where(inFile.Contains))
                    Visit(dependency);
                ordered.Add(type);
            }
        }

        private static SortedSet<string> Includes(string file, List<NamedType> types)
        {
            var includes = new SortedSet<string>(StringComparer.Ordinal);
            foreach (var dependency in types.SelectMany(Dependencies))
            {
                if (dependency.IdlFile != file) includes.Add(dependency.IdlFile);
            }
            return includes;
        }

        private static IEnumerable<NamedType> Dependencies(NamedType type)
        {
            if (type is not StructType structType) yield break;

            foreach (var field in structType.Fields)
            {
                if (SchemaDiscovery.ReferencedStruct(field.Shape) is { } referencedStruct) yield return referencedStruct;
                if (ReferencedEnum(field.Shape) is { } referencedEnum) yield return referencedEnum;
            }
        }

        private static EnumType? ReferencedEnum(Shape shape) => shape switch
        {
            EnumShape e => e.Type,
            SequenceShape { Element: EnumShape e } => e.Type,
            ArrayShape { Element: EnumShape e } => e.Type,
            _ => null,
        };

        /// <summary>Include guards would silently drop a type caught in an include cycle, so reject cycles.</summary>
        private static void ReportIncludeCycles(DdsSchema schema, Dictionary<string, SortedSet<string>> includes)
        {
            var done = new HashSet<string>();
            var path = new List<string>();

            foreach (var file in includes.Keys.Order(StringComparer.Ordinal))
                Visit(file);

            void Visit(string file)
            {
                if (done.Contains(file) || !includes.ContainsKey(file)) return;

                int index = path.IndexOf(file);
                if (index >= 0)
                {
                    var cycle = path.Skip(index).Append(file).Select(f => $"{f}.idl");
                    schema.Diagnostics.Add(new SchemaDiagnostic(
                        $"IDL files include each other: {string.Join(" -> ", cycle)}. Move the types involved into one file with [DdsIdlFile].", null));
                    return;
                }

                path.Add(file);
                foreach (var include in includes[file])
                    Visit(include);
                path.RemoveAt(path.Count - 1);
                done.Add(file);
            }
        }
    }
}
