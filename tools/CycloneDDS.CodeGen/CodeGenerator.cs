using System.Text;
using CycloneDDS.CodeGen.Discovery;
using CycloneDDS.CodeGen.Emit;
using CycloneDDS.CodeGen.Model;
using CycloneDDS.Compiler.Common;
using CycloneDDS.Compiler.Common.IdlJson;

namespace CycloneDDS.CodeGen
{
    /// <summary>
    /// Runs the generation pipeline for one project: discover types, emit IDL, run idlc for the
    /// topic descriptors, then emit the C# type support.
    /// </summary>
    public sealed class CodeGenerator
    {
        private const string IdlMapFile = "CycloneDDS.IdlMap.g.cs";

        /// <summary>Thrown when the schema is invalid; the message lists every diagnostic.</summary>
        public sealed class SchemaException(IReadOnlyList<SchemaDiagnostic> diagnostics)
            : Exception(string.Join(Environment.NewLine, diagnostics))
        {
            public IReadOnlyList<SchemaDiagnostic> Diagnostics { get; } = diagnostics;
        }

        /// <summary>
        /// Generates IDL and C# for the sources under <paramref name="sourceDir"/> into <paramref name="outputDir"/>.
        /// IDL of referenced assemblies must already be in <paramref name="outputDir"/> (the MSBuild targets copy it there).
        /// </summary>
        /// <exception cref="SchemaException">The DDS types are invalid.</exception>
        public void Generate(string sourceDir, string outputDir, IEnumerable<string>? referencePaths = null)
        {
            Generate(SchemaDiscovery.Discover(sourceDir, referencePaths), outputDir);
        }

        /// <inheritdoc cref="Generate(string, string, IEnumerable{string}?)"/>
        public void Generate(DdsSchema schema, string outputDir)
        {
            ThrowIfInvalid(schema);
            Directory.CreateDirectory(outputDir);

            var idlFiles = IdlEmitter.Emit(schema);
            ThrowIfInvalid(schema);
            CheckIncludesExist(schema, idlFiles, outputDir);

            foreach (var (file, text) in idlFiles)
                WriteIfChanged(Path.Combine(outputDir, $"{file}.idl"), text);

            var generated = new HashSet<string>(StringComparer.Ordinal) { Path.Combine(outputDir, IdlMapFile) };
            WriteIfChanged(Path.Combine(outputDir, IdlMapFile), EmitIdlMap(schema));

            var descriptors = RunIdlc(idlFiles.Keys, outputDir);
            foreach (var type in schema.Structs)
            {
                if (!descriptors.TryGetValue(type.IdlName, out var descriptor))
                    throw new InvalidOperationException($"idlc produced no topic descriptor for '{type.IdlName}' ({type.IdlFile}.idl).");

                string path = Path.Combine(outputDir, $"{type.CSharpFullName}.g.cs");
                WriteIfChanged(path, TypeSupportEmitter.Emit(type, descriptor));
                generated.Add(path);
            }

            // Output of types that no longer exist would otherwise keep compiling
            foreach (var file in Directory.GetFiles(outputDir, "*.cs"))
            {
                if (!generated.Contains(file)) File.Delete(file);
            }
        }

        private static void ThrowIfInvalid(DdsSchema schema)
        {
            if (schema.HasErrors) throw new SchemaException(schema.Diagnostics);
        }

        /// <summary>
        /// Every included file must be a local one or a referenced assembly's IDL already copied
        /// into the output directory; otherwise idlc fails with a less helpful message.
        /// </summary>
        private static void CheckIncludesExist(DdsSchema schema, Dictionary<string, string> idlFiles, string outputDir)
        {
            var externals = schema.Structs
                .SelectMany(s => s.Fields)
                .Select(f => ReferencedType(f.Shape))
                .Where(t => t is { IsExternal: true })
                .Select(t => t!)
                .DistinctBy(t => t.CSharpFullName);

            foreach (var type in externals)
            {
                if (idlFiles.ContainsKey(type.IdlFile) || File.Exists(Path.Combine(outputDir, $"{type.IdlFile}.idl"))) continue;

                schema.Diagnostics.Add(new SchemaDiagnostic(
                    $"'{type.CSharpFullName}' is declared in {type.IdlFile}.idl, which is not in '{outputDir}'. " +
                    "It should have been copied from the referenced assembly's output; rebuild that assembly.", null));
            }

            ThrowIfInvalid(schema);
        }

        private static NamedType? ReferencedType(Shape shape) => shape switch
        {
            StructShape s => s.Type,
            EnumShape e => e.Type,
            SequenceShape seq => ReferencedType(seq.Element),
            ArrayShape array => ReferencedType(array.Element),
            _ => null,
        };

        /// <summary>Records where each local type's IDL lives, for projects that reference this assembly.</summary>
        private static string EmitIdlMap(DdsSchema schema)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated>Generated by CycloneDDS.CodeGen. Do not edit.</auto-generated>");
            foreach (var type in schema.LocalTypes)
                sb.AppendLine($"[assembly: global::CycloneDDS.Schema.DdsIdlMapping(\"{type.CSharpFullName}\", \"{type.IdlFile}\", \"{type.IdlModule}\")]");
            return sb.ToString();
        }

        /// <summary>Runs idlc's JSON backend on each local IDL file and indexes the topic descriptors by IDL name.</summary>
        private static Dictionary<string, JsonTopicDescriptor> RunIdlc(IEnumerable<string> files, string outputDir)
        {
            var descriptors = new Dictionary<string, JsonTopicDescriptor>(StringComparer.Ordinal);
            var runner = new IdlcRunner();
            var parser = new IdlJsonParser();
            string jsonDir = Path.Combine(outputDir, "temp_json");

            foreach (var file in files)
            {
                var result = runner.RunIdlc(Path.Combine(outputDir, $"{file}.idl"), jsonDir, outputDir);
                if (result.ExitCode != 0)
                {
                    // MSBuild reports only canonical lines as errors, so idlc's output goes on one line
                    string output = string.Join(" | ", $"{result.StandardError}{result.StandardOutput}"
                        .Split('\n', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries));
                    throw new InvalidOperationException($"idlc failed on {file}.idl (exit {result.ExitCode}): {output}");
                }

                foreach (var type in parser.Parse(Path.Combine(jsonDir, $"{file}.json")))
                {
                    if (type.TopicDescriptor != null) descriptors[type.Name] = type.TopicDescriptor;
                }
            }

            return descriptors;
        }

        private static void WriteIfChanged(string path, string content)
        {
            if (File.Exists(path) && File.ReadAllText(path) == content) return;
            File.WriteAllText(path, content);
        }
    }
}
