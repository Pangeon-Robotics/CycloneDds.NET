using System;
using System.Linq;
using CycloneDDS.CodeGen.Emit;
using Xunit;

namespace CycloneDDS.CodeGen.Tests
{
    public class IdlEmitterTests : CodeGenTestBase
    {
        private static string EmitSingle(string source) => IdlEmitter.Emit(DiscoverValid(source)).Single().Value;

        [Fact]
        public void File_HasStableHeaderGuardAndLayout()
        {
            string idl = EmitSingle(@"
using System.Collections.Generic;
using CycloneDDS.Schema;
namespace std_msgs.msg.dds_
{
    [DdsStruct] public partial struct String_ { [DdsBound(10)] public string data; public List<double> values; }
}");

            Assert.Equal(
                """
                // Generated by CycloneDDS.CodeGen from C# sources. Do not edit.
                #ifndef CYCLONEDDS_GENERATED_FILE0_IDL
                #define CYCLONEDDS_GENERATED_FILE0_IDL

                module std_msgs {
                    module msg {
                        module dds_ {
                            @final
                            struct String_ {
                                string<10> data;
                                sequence<double> values;
                            };

                        };
                    };
                };

                #endif // CYCLONEDDS_GENERATED_FILE0_IDL

                """.ReplaceLineEndings(), idl.ReplaceLineEndings());
        }

        /// <summary>
        /// Types from several namespaces in one file: each must follow what it references, so
        /// modules are reopened rather than emitted alphabetically.
        /// </summary>
        [Fact]
        public void TypesAcrossModules_AreOrderedByDependency()
        {
            string idl = EmitSingle(@"
using CycloneDDS.Schema;
namespace a_first { [DdsStruct] public partial struct User { public z_last.Used U; } }
namespace z_last { [DdsStruct] public partial struct Used { public int X; } }");

            int used = idl.IndexOf("struct Used", StringComparison.Ordinal);
            int user = idl.IndexOf("struct User", StringComparison.Ordinal);
            Assert.True(used >= 0 && used < user, idl);
            Assert.Contains("::z_last::Used U;", idl);
        }

        [Fact]
        public void TypeSpecs_ForEveryShape()
        {
            string idl = EmitSingle(@"
using System.Collections.Generic;
using System.Runtime.CompilerServices;
using CycloneDDS.Schema;
namespace T
{
    public enum E { A, B }
    [InlineArray(4)] public struct Four { private int _e; }
    [DdsStruct] public partial struct S
    {
        public bool b; public byte u8; public sbyte i8; public short i16; public ushort u16;
        public int i32; public uint u32; public long i64; public ulong u64; public float f; public double d;
        public E e;
        [DdsBound(3)] public List<int> bounded;
        [DdsElementBound(5)] public string[] boundedElements;
        [ArrayLength(2)] public E[] fixedEnums;
        public Four inline;
        [DdsWideString] public string wide;
        [DdsWideString, DdsBound(8)] public string boundedWide;
        [DdsWideString] public List<string> wides;
    }
}");

            string[] expected =
            [
                "boolean b;", "octet u8;", "int8 i8;", "int16 i16;", "uint16 u16;",
                "int32 i32;", "uint32 u32;", "int64 i64;", "uint64 u64;", "float f;", "double d;",
                "::T::E e;",
                "sequence<int32, 3> bounded;",
                "sequence<string<5> > boundedElements;",
                "::T::E fixedEnums[2];",
                "int32 inline[4];",
                "wstring wide;",
                "wstring<8> boundedWide;",
                "sequence<wstring> wides;",
            ];
            foreach (var line in expected)
                Assert.Contains(line, idl);
        }

        [Fact]
        public void Enums_BitBoundAndValues()
        {
            var files = IdlEmitter.Emit(DiscoverValid(@"
namespace T
{
    public enum Sequential { A, B, C }
    public enum Gapped : ushort { A = 1, B = 5 }
}"));
            string idl = files.Single().Value;

            Assert.Contains("enum Sequential {\n        A,\n        B,\n        C\n    };".ReplaceLineEndings(), idl.ReplaceLineEndings());
            Assert.Contains("@bit_bound(16)", idl);
            Assert.Contains("@value(1) A,", idl);
            Assert.Contains("@value(5) B", idl);
        }

        [Fact]
        public void MemberNamedLikeIdlKeyword_IsEscaped()
        {
            string idl = EmitSingle(@"
using CycloneDDS.Schema;
namespace T { [DdsStruct] public partial struct S { public int module; public int Sequence; } }");

            Assert.Contains("int32 _module;", idl);
            Assert.Contains("int32 _Sequence;", idl);
        }

        [Fact]
        public void Includes_AreSortedAndExcludeOwnFile()
        {
            var files = IdlEmitter.Emit(DiscoverValid(
                @"using CycloneDDS.Schema; namespace T { [DdsStruct] public partial struct User { public Z z; public A a; public Local l; } [DdsStruct] public partial struct Local { public int X; } }",
                @"using CycloneDDS.Schema; namespace T { [DdsStruct] public partial struct Z { public int X; } }",
                @"using CycloneDDS.Schema; namespace T { [DdsStruct] public partial struct A { public int X; } }"));

            string user = files["File0"];
            int file1 = user.IndexOf("#include \"File1.idl\"", StringComparison.Ordinal);
            int file2 = user.IndexOf("#include \"File2.idl\"", StringComparison.Ordinal);
            Assert.True(file1 >= 0 && file1 < file2, user);
            Assert.DoesNotContain("File0.idl", user);
        }
    }
}
